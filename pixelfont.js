var ROWS = 7

var DAYS = ["PAZAR", "PAZARTESİ", "SALI", "ÇARŞAMBA", "PERŞEMBE", "CUMA", "CUMARTESİ"]
var MONTHS = ["OCAK", "ŞUBAT", "MART", "NİSAN", "MAYIS", "HAZİRAN",
              "TEMMUZ", "AĞUSTOS", "EYLÜL", "EKİM", "KASIM", "ARALIK"]

function glyph(ch) {
    var g = GLYPHS[ch]
    if (g !== undefined) return g
    g = GLYPHS[String(ch).toUpperCase()]
    return g !== undefined ? g : GLYPHS[" "]
}

function width(ch) {
    return glyph(ch)[0].length
}

// Total column count a string occupies, including the blank columns between
// glyphs. Used for implicit sizing so layouts never have to guess.
function columns(text, tracking) {
    var str = String(text)
    var total = 0
    for (var i = 0; i < str.length; i++) {
        total += width(str.charAt(i))
        if (i < str.length - 1) total += tracking
    }
    return total
}

function pad2(value) {
    return value < 10 ? "0" + value : String(value)
}

function dayName(date) {
    return DAYS[date.getDay()]
}

function dateLine(date) {
    return pad2(date.getDate()) + " " + MONTHS[date.getMonth()]
}

function fullDateLine(date) {
    return dayName(date) + " · " + dateLine(date)
}

function shortDateLine(date) {
    return pad2(date.getDate()) + " " + MONTHS[date.getMonth()].substring(0, 3)
}
